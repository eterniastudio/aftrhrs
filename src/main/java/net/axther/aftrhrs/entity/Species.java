package net.axther.aftrhrs.entity;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import net.axther.aftrhrs.AftrHrs;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.Identifier;
import net.minecraft.sounds.SoundEvent;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.Items;
import org.jspecify.annotations.Nullable;

/**
 * One Arcana creature, read from {@code data/aftrhrs/species/<id>.json} (generated by {@code mod/tools/gen_creatures.py}
 * from the MythicMobs specs and the bbmodels). Everything a creature does that differs between species is data here;
 * the base classes ({@link ArcanaCreature}, {@link ArcanaMount}, {@link ArcanaWildlife}, {@link ArcanaMonster}) read it.
 * <p>
 * Immutable and shared between the server thread and the client render thread: everything the creatures read every
 * tick (flags, object sections, the sfx event table, life timing) is resolved eagerly in the constructor, so the hot
 * paths are field loads instead of Gson {@code LinkedTreeMap} lookups. {@link #json} stays for cold paths.
 */
public final class Species {
    /** What base class and behavior a creature gets. */
    public enum Kind {
        PET, MOUNT, HOSTILE, WILDLIFE, LIVESTOCK, PARTICLES, UNDEAD, BOSS, POLICE;

        static Kind of(String s) {
            return valueOf(s.toUpperCase(Locale.ROOT));
        }

        /** Pets, mounts and tameable hostiles (and the untameable Lurefin, which shares their base). */
        public boolean tameableBase() {
            return this == PET || this == MOUNT || this == HOSTILE;
        }
    }

    /** A sound with its volume and pitch, as the live MythicMobs sound lines play it. */
    public record Sound(String id, float volume, float pitch) {
        public @Nullable SoundEvent event() {
            Identifier key = Identifier.tryParse(id.contains(":") ? id : "minecraft:" + id);
            return key == null ? null : BuiltInRegistries.SOUND_EVENT.getValue(key);
        }
    }

    /** One animation clip of the model: its length in seconds and Blockbench loop mode (loop / once / hold). */
    public record Clip(String name, float length, String loop) {
        public int ticks() {
            return Math.max(1, Math.round(length * 20));
        }

        public boolean loops() {
            return "loop".equals(loop);
        }
    }

    /** A mood rule: the clip to use while {@code condition} holds (later rules win). */
    public record Mood(String clip, String condition) {
    }

    /**
     * A natural spawn rule (MythicMobs random spawn, Action ADD), run by {@link ArcanaSpawner}. {@code structures}: the
     * spot must also be inside one of these structures (empty = anywhere in the biomes).
     */
    public record Spawn(String dimension, List<String> biomes, String rarity, String position, List<String> conditions,
                        int cap, double capRadius, List<String> structures) {
        /** SEA / WATER rules spawn in water; everything else on the ground. */
        public boolean water() {
            return "SEA".equalsIgnoreCase(position) || "WATER".equalsIgnoreCase(position);
        }
    }

    /** A drop: vanilla item or custom (ex-Oraxen) id, amount range and chance; or an XP amount. */
    public record Drop(@Nullable Item item, @Nullable String custom, int min, int max, double chance, int exp) {
    }

    public final String id;
    public final JsonObject json;
    public final Kind kind;
    public final String mythicId;
    public final String name;
    public final String model;
    public final Map<String, Clip> clips;
    public final Map<String, String> anims;
    public final List<Mood> idleMoods, walkMoods;
    public final Map<String, List<String>> pools;
    public final Map<String, Sound> flourishSounds;
    public final Map<String, Float> damageMods;
    public final List<Spawn> spawns;
    public final List<Drop> drops;
    public final List<JsonObject> abilities;
    /** Abilities' precomputed ~onTimer plan (built on first tick, after Abilities.init registered TIMERS). Server
     *  thread only; an immutable, idempotent value (a racing rebuild makes an equal one). */
    public net.axther.aftrhrs.entity.ability.Abilities.@Nullable TimerPlan timerPlan;
    public final List<String> glowBones, glowOut;
    public final float width, height, eye, shadow, nameTagY, scale;
    public final List<float[]> seats;
    /** Animation data: clip tags, states, transitions, idle pools, procedural bones (PORTING.md "Animation"). */
    public final AnimSpec anim;

    // ---- resolved once from json (see the class doc): never mutated, safe to read from any thread
    /** Every top-level key whose value is a JSON primitive that reads as true ({@link #flag}). */
    private final Set<String> trueFlags;
    /** Every top-level key whose value is a JSON object ({@link #section}). */
    private final Map<String, JsonObject> sections;
    private final boolean flyer, hostile, untameable, fights, eggOnly, noNap, panicRun, young, quietCond;
    private final double speed, followRange;
    private final @Nullable JsonObject aquatic, mount, motion;
    /** The undead variant's vanilla stand-in, upper-cased ({@code base} in the spec; "" when none). */
    public final String base;
    /** {@code despawn} in the spec ("true" when absent). */
    public final String despawn;
    /** The idle life table ({@code life}), or null; {@link #lifeEvery} is its period in ticks (0 = never). */
    public final @Nullable JsonObject life;
    public final int lifeEvery;
    /** {@code life.chance}, or NaN when the spec leaves it to the base class default: use {@link #lifeChance(double)}. */
    private final double lifeChance;
    /** Aquatic creatures: swim straight after the owner / hold depth when idle ({@code aquatic.follow / hover}). */
    public final boolean aquaticFollow, aquaticHover;
    /** The sfx profile's events (event name to its info object; empty without a profile). */
    public final Map<String, JsonObject> sfxEvents;
    /** Whether the sfx profile has the per-tick driven splash / flap / gallop events. */
    public final boolean sfxSplash, sfxFlap, sfxGallop;

    private Species(String id, JsonObject j) {
        this.id = id;
        this.json = j;
        this.kind = Kind.of(str(j, "kind", "pet"));
        this.mythicId = str(j, "mm_id", id);
        this.name = str(j, "name", id);
        this.model = str(j, "model", null);
        Map<String, Clip> clips = new LinkedHashMap<>();
        if (j.has("clips")) {
            for (Map.Entry<String, JsonElement> e : j.getAsJsonObject("clips").entrySet()) {
                JsonObject c = e.getValue().getAsJsonObject();
                clips.put(e.getKey(), new Clip(e.getKey(), c.get("length").getAsFloat(), str(c, "loop", "once")));
            }
        }
        this.clips = Collections.unmodifiableMap(clips);
        Map<String, String> anims = new LinkedHashMap<>();
        if (j.has("anims")) j.getAsJsonObject("anims").entrySet().forEach(e -> anims.put(e.getKey(), e.getValue().getAsString()));
        this.anims = Collections.unmodifiableMap(anims);
        List<Mood> idle = new ArrayList<>(), walk = new ArrayList<>();
        if (j.has("moods")) {
            JsonObject m = j.getAsJsonObject("moods");
            for (JsonElement e : m.getAsJsonArray("idle")) idle.add(new Mood(e.getAsJsonArray().get(0).getAsString(), e.getAsJsonArray().get(1).getAsString()));
            for (JsonElement e : m.getAsJsonArray("walk")) walk.add(new Mood(e.getAsJsonArray().get(0).getAsString(), e.getAsJsonArray().get(1).getAsString()));
        }
        this.idleMoods = List.copyOf(idle);
        this.walkMoods = List.copyOf(walk);
        Map<String, List<String>> pools = new LinkedHashMap<>();
        if (j.has("pools")) j.getAsJsonObject("pools").entrySet().forEach(e -> pools.put(e.getKey(), strings(e.getValue().getAsJsonArray())));
        this.pools = Collections.unmodifiableMap(pools);
        Map<String, Sound> fs = new LinkedHashMap<>();
        if (j.has("flourish_sounds")) j.getAsJsonObject("flourish_sounds").entrySet().forEach(e -> fs.put(e.getKey(), sound(e.getValue().getAsJsonObject())));
        this.flourishSounds = Collections.unmodifiableMap(fs);
        Map<String, Float> mods = new LinkedHashMap<>();
        if (j.has("damage_mods")) j.getAsJsonObject("damage_mods").entrySet().forEach(e -> mods.put(e.getKey(), e.getValue().getAsFloat()));
        this.damageMods = Collections.unmodifiableMap(mods);
        List<Spawn> spawns = new ArrayList<>();
        if (j.has("spawns")) {
            for (JsonElement e : j.getAsJsonArray("spawns")) {
                JsonObject s = e.getAsJsonObject();
                spawns.add(new Spawn(str(s, "dimension", "minecraft:overworld"), strings(s.getAsJsonArray("biomes")), str(s, "rarity", "uncommon"),
                        str(s, "position", "LAND"), s.has("conditions") ? strings(s.getAsJsonArray("conditions")) : List.of(),
                        s.has("cap") ? s.get("cap").getAsInt() : -1, s.has("cap_radius") ? s.get("cap_radius").getAsDouble() : 48,
                        s.has("structures") ? strings(s.getAsJsonArray("structures")) : List.of()));
            }
        }
        this.spawns = List.copyOf(spawns);
        List<Drop> drops = new ArrayList<>();
        if (j.has("drops")) {
            for (JsonElement e : j.getAsJsonArray("drops")) {
                JsonObject d = e.getAsJsonObject();
                double chance = d.has("chance") ? d.get("chance").getAsDouble() : 1;
                if (d.has("exp")) {
                    drops.add(new Drop(null, null, 0, 0, chance, d.get("exp").getAsInt()));
                } else {
                    Item item = d.has("item") ? item(d.get("item").getAsString()) : null;
                    drops.add(new Drop(item, d.has("custom") ? d.get("custom").getAsString() : null,
                            d.get("min").getAsInt(), d.get("max").getAsInt(), chance, 0));
                }
            }
        }
        this.drops = List.copyOf(drops);
        List<JsonObject> ab = new ArrayList<>();
        String key = j.has("abilities") ? "abilities" : "lines";
        if (j.has(key)) for (JsonElement e : j.getAsJsonArray(key)) ab.add(e.getAsJsonObject());
        this.abilities = List.copyOf(ab);
        this.glowBones = j.has("glow_bones") ? strings(j.getAsJsonArray("glow_bones")) : List.of();
        this.glowOut = j.has("glow_out") ? strings(j.getAsJsonArray("glow_out")) : List.of();
        this.scale = (float) dbl(j, "scale", 1);
        float[] box = floats(j, "hitbox");
        if (box == null) box = floats(j, "model_hitbox");
        if (box == null) box = new float[] {0.6f, 0.8f};
        this.width = box[0];
        this.height = box[1];
        this.eye = j.has("eye") ? j.get("eye").getAsFloat() : height * 0.85f;
        this.shadow = (float) dbl(j, "shadow", 0.5);
        this.nameTagY = (float) dbl(j, "name_tag_y", height + 0.3);
        List<float[]> seats = new ArrayList<>();
        if (j.has("seats")) for (JsonElement e : j.getAsJsonArray("seats")) seats.add(floats(e.getAsJsonArray()));
        this.seats = List.copyOf(seats);
        Set<String> flags = new HashSet<>();
        Map<String, JsonObject> secs = new HashMap<>();
        for (Map.Entry<String, JsonElement> e : j.entrySet()) {
            JsonElement v = e.getValue();
            if (v.isJsonObject()) secs.put(e.getKey(), v.getAsJsonObject());
            else if (v.isJsonPrimitive() && v.getAsBoolean()) flags.add(e.getKey());   // the same parse the old flag() did
        }
        this.trueFlags = Set.copyOf(flags);
        this.sections = Map.copyOf(secs);
        this.flyer = flag("flyer");
        this.hostile = flag("hostile");
        this.untameable = flag("untameable");
        this.fights = flag("fights");
        this.eggOnly = flag("egg_only");
        this.noNap = flag("no_nap");
        this.panicRun = flag("panic_run");
        this.young = j.has("young_of");
        this.quietCond = j.has("quiet_cond");
        this.speed = dbl(j, "speed", 0.25);
        this.followRange = dbl(j, "follow_range", 16);
        this.aquatic = section("aquatic");
        this.mount = section("mount");
        this.motion = mount != null && mount.has("motion") ? mount.getAsJsonObject("motion") : null;
        this.base = str(j, "base", "").toUpperCase(Locale.ROOT);
        this.despawn = str(j, "despawn", "true");
        this.life = section("life");
        this.lifeEvery = life == null ? 0 : (int) dbl(life, "every", 100);
        this.lifeChance = life != null && life.has("chance") && life.get("chance").isJsonPrimitive() ? life.get("chance").getAsDouble() : Double.NaN;
        this.aquaticFollow = aquatic != null && aquatic.has("follow") && aquatic.get("follow").getAsBoolean();
        this.aquaticHover = aquatic != null && aquatic.has("hover") && aquatic.get("hover").getAsBoolean();
        JsonObject sfx = section("sfx");
        Map<String, JsonObject> ev = new HashMap<>();
        if (sfx != null && sfx.has("events")) {
            for (Map.Entry<String, JsonElement> e : sfx.getAsJsonObject("events").entrySet()) ev.put(e.getKey(), e.getValue().getAsJsonObject());
        }
        this.sfxEvents = Collections.unmodifiableMap(ev);
        this.sfxSplash = ev.containsKey("splash");
        this.sfxFlap = ev.containsKey("flap");
        this.sfxGallop = ev.containsKey("gallop");
        this.anim = new AnimSpec(j.has("anim") && j.get("anim").isJsonObject() ? j.getAsJsonObject("anim") : null, speed);
    }

    // ------------------------------------------------------------------ typed accessors

    public double health() {
        return dbl(json, "health", 10);
    }

    public double damage() {
        return dbl(json, "damage", 0);
    }

    public double speed() {
        return speed;
    }

    public double followRange() {
        return followRange;
    }

    /** A top-level boolean of the spec (a primitive that reads as true). A set lookup, fine on hot paths. */
    public boolean flag(String key) {
        return trueFlags.contains(key);
    }

    public boolean flyer() {
        return flyer;
    }

    public boolean hostile() {
        return hostile;
    }

    public boolean untameable() {
        return untameable;
    }

    public boolean fights() {
        return fights;
    }

    /** Only hatched from a pet egg: never spawns wild and is never dropped as a wild one. */
    public boolean eggOnly() {
        return eggOnly;
    }

    /** A staying pet that never naps at night. */
    public boolean noNap() {
        return noNap;
    }

    /** Wildlife that runs (rather than walks) while spooked. */
    public boolean panicRun() {
        return panicRun;
    }

    /** The spec has a {@code quiet_cond} (silent while dormant, like the Vinebound lying in wait). */
    public boolean quietCond() {
        return quietCond;
    }

    /** {@code life.chance}, or {@code def} when the spec does not set one (the base classes use different defaults). */
    public double lifeChance(double def) {
        return Double.isNaN(lifeChance) ? def : lifeChance;
    }

    public boolean young() {
        return young;
    }

    public @Nullable String youngOf() {
        return str(json, "young_of", null);
    }

    public @Nullable String youngId() {
        return str(json, "young", null);
    }

    public boolean mount() {
        return kind == Kind.MOUNT;
    }

    public @Nullable JsonObject aquatic() {
        return aquatic;
    }

    public @Nullable JsonObject mountData() {
        return mount;
    }

    public @Nullable JsonObject motion() {
        return motion;
    }

    /** A top-level object of the spec, or null (absent or not an object). A map lookup, fine on hot paths. */
    public @Nullable JsonObject section(String key) {
        return sections.get(key);
    }

    /** The tame item, or null for untameable creatures. */
    public @Nullable Item tameItem() {
        JsonObject t = section("tame");
        return t == null ? null : item(t.get("item").getAsString());
    }

    /** A custom (ex-Oraxen) tame item id such as {@code arcana_seashell}, or null. */
    public @Nullable String tameCustom() {
        JsonObject t = section("tame");
        return t == null ? null : str(t, "custom", null);
    }

    public double tameChance() {
        JsonObject t = section("tame");
        return t == null ? 0 : dbl(t, "chance", 0.33);
    }

    public @Nullable Item tameReturn() {
        JsonObject t = section("tame");
        return t == null || !t.has("return") ? null : item(t.get("return").getAsString());
    }

    public @Nullable Item healItem() {
        JsonObject h = section("heal");
        return h == null ? null : item(h.get("item").getAsString());
    }

    public float healAmount() {
        JsonObject h = section("heal");
        return h == null ? 4 : (float) dbl(h, "amount", 4);
    }

    public @Nullable Sound sound(String key) {
        JsonObject s = section("sounds");
        return s == null || !s.has(key) || !s.get(key).isJsonObject() ? null : sound(s.getAsJsonObject(key));
    }

    public int soundEvery(String key, int def) {
        JsonObject s = section("sounds");
        return s == null || !s.has(key) ? def : s.get(key).getAsInt();
    }

    public double soundChance(String key, double def) {
        JsonObject s = section("sounds");
        return s == null || !s.has(key) ? def : s.get(key).getAsDouble();
    }

    /** The clip for a role (sit, eat, happy, attack ...) if the model has it. */
    public @Nullable String anim(String role) {
        String a = anims.get(role);
        if (a != null && clips.containsKey(a)) return a;
        return clips.containsKey(role) ? role : null;
    }

    public boolean has(String clip) {
        return clip != null && clips.containsKey(clip);
    }

    public int clipTicks(String clip, int def) {
        Clip c = clips.get(clip);
        return c == null ? def : c.ticks();
    }

    /** Base idle / walk clips: a flyer hovers and flies, everything else idles and walks. */
    public String baseIdle() {
        String b = str(json, "base_idle", null);
        if (b != null && has(b)) return b;
        return flyer() && has("hover") ? "hover" : "idle";
    }

    public String baseWalk() {
        String b = str(json, "base_walk", null);
        if (b != null && has(b)) return b;
        return flyer() && has("fly") ? "fly" : "walk";
    }

    public Identifier entityId() {
        return AftrHrs.id(id);
    }

    // ------------------------------------------------------------------ json helpers

    static Sound sound(JsonObject o) {
        return new Sound(o.get("id").getAsString(), (float) dbl(o, "volume", 1), (float) dbl(o, "pitch", 1));
    }

    public static @Nullable String str(JsonObject o, String k, @Nullable String def) {
        return o.has(k) && !o.get(k).isJsonNull() ? o.get(k).getAsString() : def;
    }

    public static double dbl(JsonObject o, String k, double def) {
        return o.has(k) && o.get(k).isJsonPrimitive() ? o.get(k).getAsDouble() : def;
    }

    static List<String> strings(JsonArray a) {
        List<String> out = new ArrayList<>();
        for (JsonElement e : a) out.add(e.getAsString());
        return List.copyOf(out);
    }

    private static float @Nullable [] floats(JsonObject o, String k) {
        return o.has(k) && o.get(k).isJsonArray() ? floats(o.getAsJsonArray(k)) : null;
    }

    private static float[] floats(JsonArray a) {
        float[] f = new float[a.size()];
        for (int i = 0; i < f.length; i++) f[i] = a.get(i).getAsFloat();
        return f;
    }

    public static @Nullable Item item(String id) {
        Identifier key = Identifier.tryParse(id);
        if (key == null) return null;
        Item item = BuiltInRegistries.ITEM.getValue(key);
        return item == Items.AIR ? null : item;
    }

    // ------------------------------------------------------------------ loading

    /** Loads every species named in {@code data/aftrhrs/species/index.json} from the mod's resources. */
    static List<Species> loadAll() {
        List<Species> out = new ArrayList<>();
        JsonObject index = read("index");
        for (JsonElement e : index.getAsJsonArray("species")) {
            String id = e.getAsString();
            out.add(new Species(id, read(id)));
        }
        return out;
    }

    private static JsonObject read(String name) {
        String path = "/data/aftrhrs/species/" + name + ".json";
        try (InputStream in = Species.class.getResourceAsStream(path)) {
            if (in == null) throw new IllegalStateException("Missing species file " + path);
            return JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
        } catch (java.io.IOException ex) {
            throw new IllegalStateException("Cannot read " + path, ex);
        }
    }

    @Override
    public String toString() {
        return "Species[" + id + "]";
    }
}
