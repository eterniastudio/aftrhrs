#!/usr/bin/env python3
"""Builds the fishing species models that live in the repo (the 75 real-world species added with the fish expansion;
the first 22 fish come from the Oraxen pack as before) and their content-item source.

Writes (Oraxen format, read by tools/gen_content.py as its in-repo content root, --content, default mod/content):
  mod/content/pack/models/arcana/fishing/fish_<id>.json         the item model (side-on fish, display poses)
  mod/content/pack/textures/arcana/fishing/3d/fish_<id>.png     its texture atlas
  mod/content/items/arcana_fishing.yml                          the items: name (coloured by rarity), lore, model
and the Blockbench sources to mod/build/fishart/bbmodel/ (not in git). Names and rarities come from
src/main/resources/feather/fishing.yml; lore and the art from species_fresh.py / species_salt.py.

Run:  python mod/tools/fishart/build.py [fish_id ...]     (needs Pillow)
      python mod/tools/fishart/sheet.py                     contact sheets (needs numpy and the plants3d renderer)
Then: python mod/tools/gen_content.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import ik  # noqa: E402
import species_fresh  # noqa: E402
import species_salt  # noqa: E402

MOD = os.path.dirname(os.path.dirname(HERE))
CONTENT = os.path.join(MOD, 'content')
FISHING_YML = os.path.join(MOD, 'src', 'main', 'resources', 'feather', 'fishing.yml')
COLOR = {'common': 'white', 'uncommon': 'green', 'rare': 'blue', 'legendary': 'gold'}

ALL = species_fresh.REG + species_salt.REG


def species_table():
    """{id: (name, rarity)} from fishing.yml's species section (one flow mapping per species)."""
    txt = open(FISHING_YML, encoding='utf-8').read()
    sec = txt.split('\nspecies:\n', 1)[1].split('\nitems:\n', 1)[0]
    out = {}
    for m in re.finditer(r'^  ([a-z_]+): \{name: ([^,]+), rarity: (\w+)', sec, re.M):
        out[m.group(1)] = (m.group(2).strip(), m.group(3))
    return out


def yq(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def write_items(table):
    lines = ['# Generated by mod/tools/fishart/build.py: the fishing species whose art lives in the repo. Names and',
             '# rarities follow src/main/resources/feather/fishing.yml. Read by tools/gen_content.py (--content).', '']
    for sid, name, lore, fn, disp in ALL:
        key = sid[len('fish_'):]
        yname, rarity = table.get(key, (name, 'common'))
        lines += ['arcana_%s:' % sid,
                  '  itemname: %s' % yq('<%s>%s' % (COLOR.get(rarity, 'white'), yname)),
                  '  material: COD',
                  '  lore:',
                  '  - %s' % yq('<gray>' + lore),
                  '  pack:',
                  '    generate_model: false',
                  '    model: arcana/fishing/%s' % sid,
                  '']
    path = os.path.join(CONTENT, 'items', 'arcana_fishing.yml')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    return path


def main(names):
    table = species_table()
    missing = [sid for sid, *_ in ALL if sid[5:] not in table]
    if missing:
        sys.exit('not in fishing.yml species: %s' % missing)
    seen = set()
    for sid, name, lore, fn, disp in ALL:
        if sid in seen:
            sys.exit('built twice: ' + sid)
        seen.add(sid)
        if names and sid not in names and sid[5:] not in names:
            continue
        path = ik.build(fn, 'fishing', sid, disp=disp, gui_light='side', particle='arcana/fishing/3d/' + sid)
        print(os.path.relpath(path, MOD))
    print(write_items(table))
    print('%d species' % len(ALL))


if __name__ == '__main__':
    main(set(sys.argv[1:]))
