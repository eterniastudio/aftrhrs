def bow(long, pull=None):
    sprite, (tip, heel) = bow_pair(pull == 2, long)
    points = [tip]
    if pull is not None:
        points.append(((9, 9), (10, 10), (12, 12))[pull])
    points.append(heel)
    return sprite.line('string', points, 3, behind=True)


