def mold(base, imprint):
    boxed = base == 'sand'
    if boxed:
        sprite = tray().stamp('sand', 3, 3,
            '2222222222', '2333333334', '2333433334', '2333333334',
            '2333333434', '2333333334', '2343333334', '2333333334',
            '2333333334', '2444444444')
    else:
        sprite = Sprite().stamp(base, 1, 1,
            '...12333210', '..1455544430', '.154333333420', '15433333333420',
            '14333333333420', '14333333333420', '14333333333420', '14333333333420',
            '14333333333420', '14333333333420', '.4544444444420', '.143333333320',
            '..2322222220', '...00000000')
    if imprint is None:
        return sprite
    x0 = min(x for x, y in imprint.pixels)
    y0 = min(y for x, y in imprint.pixels)
    w = max(x for x, y in imprint.pixels) - x0 + 1
    h = max(y for x, y in imprint.pixels) - y0 + 1
    # Scale against the longest edge and retain thin features like bowstrings.
    scale = min(1, 8 / max(w, h))
    left = (16 - round(w * scale)) // 2
    top = (15 - round(h * scale)) // 2
    cavity = {(left + int((x - x0 + .5) * scale), top + int((y - y0 + .5) * scale))
              for x, y in imprint.pixels}
    for x, y in cavity:
        if (x, y + 1) not in cavity:
            sprite.dot(base, x, y + 1, 4)
        if (x + 1, y) not in cavity:
            sprite.dot(base, x + 1, y, 4)
    for x, y in cavity:
        dark = (x - 1, y) not in cavity or (x, y - 1) not in cavity
        sprite.dot(base, x, y, 0 if dark else 1)
    return sprite

