"""Native 16px drawings for the Anvil & Ember item atlas.

Digits index a material ramp from darkest (0) to lightest (5). Dots leave the
canvas underneath visible. The last stroke at each pixel owns that pixel, so
the exported material layers fit together without overlapping.
"""
from PIL import Image, ImageDraw


class Sprite:
    def __init__(self):
        self.pixels = {}

    def stamp(self, layer, x, y, *rows):
        for dy, row in enumerate(rows):
            for dx, shade in enumerate(row):
                if shade != '.':
                    self.dot(layer, x + dx, y + dy, int(shade))
        return self

    def dot(self, layer, x, y, shade):
        assert 0 <= x < 16 and 0 <= y < 16, (layer, x, y)
        self.pixels[x, y] = (layer, shade)

    def line(self, layer, points, shade, *, behind=False):
        mask = Image.new('1', (16, 16))
        ImageDraw.Draw(mask).line(points, fill=1)
        for y in range(16):
            for x in range(16):
                if mask.getpixel((x, y)) and (not behind or (x, y) not in self.pixels):
                    self.dot(layer, x, y, shade)
        return self


def face(x, y, *rows):
    return Sprite().stamp('body', x, y, *rows)


# Haft rails use the same light direction on every tool. Two leather turns
# make the grip readable at native scale, with a ferrule at the other end.
def haft(end, *, wide=False, start=1, grip=True):
    sprite = Sprite()
    for x in range(start, end + 1):
        y = 15 - x
        if x < end:
            sprite.dot('handle', x, y + 1, 0)
        sprite.dot('handle', x, y, 3 if x % 4 else 2)
        sprite.dot('handle', x, y - 1, 4 if x % 3 else 5)
        if wide:
            sprite.dot('handle', x, y - 2, 1)
        if grip and x in (start + 1, start + 3):
            sprite.dot('handle', x, y, 1)
            sprite.dot('handle', x, y - 1, 2)
    sprite.dot('handle', start, 16 - start, 1)
    return sprite


